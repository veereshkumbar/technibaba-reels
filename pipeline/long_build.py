"""Make a long-form (16:9) guide video project from a spec.  usage: python3 pipeline/long_build.py SPEC.json WORKDIR
SPEC.json: {"guide": slug, "scenes": [{"id","type": title|points|compare|browser|phone|recap|outro, "chip","head","title","sub","items",...,
            "lines": [{"who": "b"|"c", "hi": devanagari, "en": roman, "pose", "expr", "big", "cap": "short *keyword* caption", "show": n, "hit": word}]}]}
Writes WORKDIR/script.py (LINES, VOICES, BEATS, LONG=True), WORKDIR/page_tpl.html and WORKDIR/layout_long. Then run the normal chain:
engine/voice.py → pipeline/beats.py → engine/build.py → pipeline/hf_build.py → hyperframes render (see LONG_FORMAT.md)."""
import sys, json, os, re
SP, W = sys.argv[1], sys.argv[2]; os.makedirs(W, exist_ok=True); spec = json.load(open(SP))
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
lines, beats, flat = [], [], []
listener = {'b': 'c', 'c': 'b'}
for s in spec['scenes']:
    s['lines_idx'] = []
    for L in s['lines']:
        i = len(lines); s['lines_idx'].append(i)
        lines.append((s['id'], L['hi'], L['en'], L['who'], ''))
        first = re.sub(r'[^a-z0-9]', '', L['en'].split()[0].lower())
        pose = L.get('pose', 'explain' if L['who'] == 'b' else 'talk'); expr = L.get('expr', 'explaining' if L['who'] == 'b' else 'happy')
        keys = [(None, L['who'], pose, expr, int(L.get('big', 0))), (None, listener[L['who']], L.get('react_pose', 'idle'), L.get('react', 'neutral'), 0)]
        for k in L.get('keys', []): keys.append(tuple(k))
        ws = [re.sub(r'[^a-z0-9]', '', w.lower()) for w in L['en'].split()]
        if len(L['en']) > 60:   # long line: a second gesture mid-line keeps a visual change every few seconds
            mid = next((w for w in ws[len(ws) // 2:] if len(w) > 2), None)
            if mid: keys.append((mid, L['who'], L.get('pose2', 'talk' if pose != 'talk' else 'explain'), expr, 0))
        b = dict(emotion=expr, action=pose, rule=L.get('rule', 'gesture + expression change each line; panel reveals on the spoken word'), keys=keys, caps=[(first, L['cap'])])
        if L.get('hit'): b['hit'] = L['hit']
        beats.append(b)
        flat.append({k: L[k] for k in ('show', 'show_new') if k in L})
scenes = [{k: v for k, v in s.items() if k not in ('lines', 'lines_idx')} | {'lines': s['lines_idx']} for s in spec['scenes']]
open(f'{W}/script.py', 'w').write('# generated by pipeline/long_build.py from ' + os.path.basename(SP) + '\nLONG=True\nLINES=' + json.dumps(lines, ensure_ascii=False, indent=0) +
    "\nVOICES={'c':('kokoro:hm_psi',1.18,1.06),'b':('file:vo_in/b_{i:02d}.wav',1.0,1.0,('kokoro:hm_omega',1.10,0.95))}\nBEATS=" + repr(beats) + '\n')
tpl = open(f'{root}/pipeline/long_page_tpl.html').read().replace('__SPEC__', json.dumps({'scenes': scenes, 'lines': flat}, ensure_ascii=False))
open(f'{W}/page_tpl.html', 'w').write(tpl); open(f'{W}/layout_long', 'w').write('16:9\n')
print('long project', W, '| scenes', len(scenes), '| lines', len(lines))
