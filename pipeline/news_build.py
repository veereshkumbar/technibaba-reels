"""Make a TechniBaba Daily news bulletin project from a spec.  usage: python3 pipeline/news_build.py SPEC.json WORKDIR
SPEC.json: {"dateLabel": "17 NOV", "scenes": [{"id", "mode": "split"|"anchor"|"card", "story": n (card number, cards only),
  "kicker": "TECH|AI|GAMING|SPACE|APPS|BUSINESS|SPORTS|FILMS|INDIA|WORLD", "icon": "gamepad|space|forum|car|server|headphones|plane|phone|chip|ai|cricket|film|rupee|globe",
  "headline": "Plain English headline with *highlight*", "stat": "short big number", "statSub": "...", "source": "Publication",
  "title": "anchor only: 'Line one|line *two*'", "list": ["anchor only: preview items"],
  "lines": [{"hi": devanagari, "en": roman, "pose", "expr", "big", "cap": "short *keyword* caption", "hit": word}]}]}
Baba is the only speaker. Writes WORKDIR/script.py, page_tpl.html, layout_news (scene modes). Then: engine/voice.py → pipeline/beats.py → engine/build.py → pipeline/hf_build.py → hyperframes render (see NEWS_FORMAT.md)."""
import sys, json, os, re
SP, W = sys.argv[1], sys.argv[2]; os.makedirs(W, exist_ok=True); spec = json.load(open(SP))
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
lines, beats = [], []
for s in spec['scenes']:
    for L in s['lines']:
        lines.append((s['id'], L['hi'], L['en'], 'b', ''))
        ws = [re.sub(r'[^a-z0-9]', '', w.lower()) for w in L['en'].split()]
        pose = L.get('pose', 'explain'); expr = L.get('expr', 'explaining')
        keys = [(None, 'b', pose, expr, int(L.get('big', 0)))]
        if len(L['en']) > 55:
            mid = next((w for w in ws[len(ws) // 2:] if len(w) > 2), None)
            if mid: keys.append((mid, 'b', L.get('pose2', 'talk' if pose != 'talk' else 'point'), expr, 0))
        b = dict(emotion=expr, action=pose, rule=L.get('rule', 'news beat: new card or gesture each line'), keys=keys, caps=[(ws[0], L['cap'])])
        if L.get('hit'): b['hit'] = L['hit']
        beats.append(b)
open(f'{W}/script.py', 'w').write('# generated by pipeline/news_build.py\nLONG=True\nNEWS=True\nLINES=' + json.dumps(lines, ensure_ascii=False, indent=0) +
    "\nVOICES={'b':('file:vo_in/b_{i:02d}.wav',1.0,1.0,('kokoro:hm_omega',1.12,0.95)),'c':('kokoro:hm_psi',1.2,1.06)}\nBEATS=" + repr(beats) + '\n')
scenes = [{k: v for k, v in s.items() if k != 'lines'} for s in spec['scenes']]
tpl = open(f'{root}/pipeline/news_page_tpl.html').read().replace('__SPEC__', json.dumps({'dateLabel': spec.get('dateLabel', ''), 'scenes': scenes}, ensure_ascii=False))
open(f'{W}/page_tpl.html', 'w').write(tpl); json.dump({s['id']: s['mode'] for s in spec['scenes']}, open(f'{W}/layout_news', 'w'))
print('news project', W, '| scenes', len(scenes), '| lines', len(lines))
